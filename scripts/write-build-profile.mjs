import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

function resolveCompiledDevTools(env) {
  const explicit = env.DSH_DEV_TOOLS
  if (explicit === '0' || explicit === 'false' || explicit === 'off') return false
  if (explicit === '1' || explicit === 'true' || explicit === 'on') return true
  const profile = env.DSH_PROFILE
  if (profile === 'production' || profile === 'release' || profile === 'prod') return false
  if (env.GITHUB_ACTIONS === 'true') return false
  return true
}

const enabled = resolveCompiledDevTools(process.env)
const out = join(dirname(fileURLToPath(import.meta.url)), '../host/src/runtime/build-profile.generated.ts')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(
  out,
  `/** Generated by scripts/write-build-profile.mjs at package time. */\nexport const COMPILED_DEV_TOOLS = ${enabled ? 'true' : 'false'}\n`,
)
process.stderr.write(`dsh-desktop: COMPILED_DEV_TOOLS=${String(enabled)}\n`)
